const byCode = new Map(US_STATES.map((s) => [s.code, s.name]));

export function usStateName(code: string): string {
  return byCode.get(code) ?? code;
}

export function isUsStateCode(code: string): boolean {
  return byCode.has(code);
}

/** Photon returns full state names for US results; the proxy and the address
 *  module both normalize to codes with this. Case-insensitive. */
const byName = new Map(US_STATES.map((s) => [s.name.toLowerCase(), s.code]));

export function usStateCodeFromName(name: string): string | null {
  const trimmed = name.trim();
  if (byCode.has(trimmed.toUpperCase()) && trimmed.length === 2) {
    return trimmed.toUpperCase();
  }
  return byName.get(trimmed.toLowerCase()) ?? null;
}
